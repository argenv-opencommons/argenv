/// A subcommand, as completions and the man page present it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Command<'a> {
    /// The word typed to run it (`create`). Must be a plain name.
    pub name: &'a str,
    /// One line saying what it does.
    pub summary: &'a str,
}

/// What the generators need to know about the program that the inputs do not say.
#[derive(Clone, Copy, Debug)]
pub struct Program<'a> {
    /// The executable's name, as typed (`snapall`).
    pub name: &'a str,
    /// The version shown in the man page footer.
    pub version: &'a str,
    /// One line, for the man page's NAME section.
    pub about: &'a str,
    /// Subcommands, in the order they should be listed. May be empty.
    pub commands: &'a [Command<'a>],
    /// `(status, meaning)` pairs for the man page's EXIT STATUS section.
    pub exit_status: &'a [(&'a str, &'a str)],
    /// Other manual pages, such as `snapper(8)`.
    pub see_also: &'a [&'a str],
    /// The man page date, `YYYY-MM-DD`. A parameter, not a clock reading, so output is
    /// reproducible.
    pub date: &'a str,
}

/// Why nothing was generated.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum GenerateError {
    /// The program name or a command name is not a plain token, so it cannot be put into shell
    /// code safely.
    InvalidName(String),
}

impl std::fmt::Display for GenerateError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            GenerateError::InvalidName(name) => write!(
                f,
                "`{name}` is not a plain name (letters, digits and `_ . -` only), so it cannot \
                 be written into a shell completion"
            ),
        }
    }
}

impl std::error::Error for GenerateError {}

/// Which shell to generate completions for.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Shell {
    /// GNU bash (3.2 and later).
    Bash,
    /// zsh, through `_arguments`.
    Zsh,
    /// fish.
    Fish,
    /// nushell, as `extern` definitions.
    Nushell,
}

impl Shell {
    /// Every supported shell.
    pub const ALL: [Shell; 4] = [Shell::Bash, Shell::Zsh, Shell::Fish, Shell::Nushell];

    /// The word for this shell on a command line: `bash`, `zsh`, `fish`, `nushell`.
    pub const fn token(self) -> &'static str {
        match self {
            Shell::Bash => "bash",
            Shell::Zsh => "zsh",
            Shell::Fish => "fish",
            Shell::Nushell => "nushell",
        }
    }

    /// The reverse of [`Shell::token`]; `nu` is accepted for nushell.
    pub fn parse(token: &str) -> Option<Shell> {
        match token {
            "bash" => Some(Shell::Bash),
            "zsh" => Some(Shell::Zsh),
            "fish" => Some(Shell::Fish),
            "nushell" | "nu" => Some(Shell::Nushell),
            _ => None,
        }
    }
}

/// Completions for `shell`.
pub fn completions(
    shell: Shell,
    program: &Program<'_>,
    records: &[Record],
) -> Result<String, GenerateError> {
    match shell {
        Shell::Bash => bash(program, records),
        Shell::Zsh => zsh(program, records),
        Shell::Fish => fish(program, records),
        Shell::Nushell => nushell(program, records),
    }
}

