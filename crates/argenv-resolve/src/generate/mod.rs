// the shared model

/// A flag, reduced to what completion needs.
#[derive(Clone, Debug)]
pub(crate) struct Flag {
    pub long: Option<String>,
    pub short: Option<String>,
    pub takes_value: bool,
    pub value_name: String,
    /// Legal values, when the input is an enumeration or a closed list.
    pub values: Vec<String>,
    pub path: bool,
    pub negatable: bool,
    pub summary: String,
    /// The declared default, as text, for non-boolean inputs.
    pub default: Option<String>,
    pub env: Vec<String>,
    pub group: String,
    /// The subcommands it belongs to; empty means all of them.
    pub scope: Vec<String>,
}

impl Flag {
    pub fn available_for(&self, command: &str) -> bool {
        self.scope.is_empty() || self.scope.iter().any(|s| s == command)
    }

    /// Spellings that can be typed, each as it appears on the command line (`--dry-run`, `-n`).
    pub fn spellings(&self) -> Vec<String> {
        let mut out = Vec::new();
        if let Some(s) = &self.short {
            out.push(format!("-{s}"));
        }
        if let Some(l) = &self.long {
            out.push(format!("--{l}"));
            if self.negatable {
                out.push(format!("--no-{l}"));
            }
        }
        out
    }
}

/// A positional argument, reduced to what completion needs.
#[derive(Clone, Debug)]
pub(crate) struct Positional {
    /// Position within its command (or absolute, when unscoped), from zero.
    pub index: usize,
    pub name: String,
    pub values: Vec<String>,
    pub path: bool,
    pub required: bool,
    pub summary: String,
    pub scope: Vec<String>,
}

impl Positional {
    pub fn available_for(&self, command: &str) -> bool {
        self.scope.iter().any(|s| s == command)
    }
}

/// A plain token: non-empty, and only characters that mean nothing special to any shell.
pub(crate) fn is_plain(token: &str) -> bool {
    !token.is_empty()
        && token.chars().all(|c| {
            c.is_ascii_alphanumeric()
                || matches!(c, '_' | '.' | '-' | ':' | '/' | '+' | '=' | '@' | ',')
        })
}

/// A name that may be written into shell code: plain, and not starting with a dash.
pub(crate) fn is_name(token: &str) -> bool {
    is_plain(token) && !token.starts_with('-')
}

/// Free text on one line: whitespace runs, newlines and control characters become one space.
pub(crate) fn one_line(text: &str) -> String {
    text.split(|c: char| c.is_whitespace() || c.is_control())
        .filter(|part| !part.is_empty())
        .collect::<Vec<_>>()
        .join(" ")
}

/// The part of the model every shell reads.
pub(crate) struct Model {
    pub flags: Vec<Flag>,
    pub positionals: Vec<Positional>,
}

pub(crate) fn model(records: &[Record]) -> Model {
    let mut flags = Vec::new();
    let mut positionals = Vec::new();
    for record in records {
        let Some(arg) = &record.arg else { continue };
        let values: Vec<String> = if matches!(record.ty.as_str(), "enum" | "list") {
            record
                .allowed
                .iter()
                .filter(|v| is_plain(v))
                .cloned()
                .collect()
        } else {
            Vec::new()
        };
        let summary = one_line(record.summary.as_deref().unwrap_or(""));
        let scope: Vec<String> = record
            .subcommands
            .iter()
            .filter(|s| is_name(s))
            .cloned()
            .collect();
        if let Some(position) = arg.position {
            positionals.push(Positional {
                index: usize::from(position),
                name: arg
                    .value_name
                    .clone()
                    .filter(|n| is_plain(n))
                    .unwrap_or_else(|| record.key.to_uppercase()),
                values,
                path: record.ty == "path",
                required: record.required,
                summary,
                scope,
            });
            continue;
        }
        let long = arg.long.clone().filter(|l| is_name(l));
        let short = arg
            .short
            .clone()
            .filter(|s| s.chars().count() == 1 && is_name(s));
        if long.is_none() && short.is_none() {
            continue;
        }
        flags.push(Flag {
            long,
            short,
            takes_value: arg.arity > 0,
            value_name: arg
                .value_name
                .clone()
                .filter(|n| is_plain(n))
                .unwrap_or_else(|| "VALUE".to_string()),
            values,
            path: record.ty == "path",
            negatable: arg.negatable,
            summary,
            default: record.default.as_ref().and_then(|v| match v {
                serde_json::Value::String(text) => Some(text.clone()),
                serde_json::Value::Number(n) => Some(n.to_string()),
                _ => None,
            }),
            env: record
                .env_names()
                .iter()
                .filter(|n| is_plain(n))
                .map(|n| (*n).to_string())
                .collect(),
            group: record
                .group
                .clone()
                .unwrap_or_else(|| "options".to_string()),
            scope,
        });
    }
    positionals.sort_by_key(|p| p.index);
    Model { flags, positionals }
}

/// The subcommands to offer: the program's own list, validated.
pub(crate) fn commands<'a>(program: &Program<'a>) -> Result<Vec<Command<'a>>, GenerateError> {
    if !is_name(program.name) {
        return Err(GenerateError::InvalidName(program.name.to_string()));
    }
    program
        .commands
        .iter()
        .map(|c| {
            if is_name(c.name) {
                Ok(*c)
            } else {
                Err(GenerateError::InvalidName(c.name.to_string()))
            }
        })
        .collect()
}

/// A shell identifier from a program name (`my-prog` becomes `my_prog`).
pub(crate) fn identifier(name: &str) -> String {
    name.chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}
