//! Everything a program ships *about* its invocation, derived from the declaration.
//!
//! A contract already says every flag, every environment variable, which subcommand each belongs
//! to, what values are legal and what each is for. Shell completions and a man page are that same
//! knowledge in other clothes, and the usual way they go wrong is by being written by hand and
//! forgotten. These generators read the declared [`Record`]s and produce:
//!
//! - completions for [bash](bash()), [zsh](zsh()), [fish](fish()) and [nushell](nushell()), in which a
//!   flag scoped to a subcommand is offered only after that subcommand, enumerated values are
//!   completed, and path-valued inputs complete file names;
//! - a [man page](man_page()).
//!
//! The records come from `Contract::records()` (generated by [`contract!`](crate::contract!)) or from a
//! published contract document, so the artifacts cannot disagree with what the program accepts.
//!
//! # Treating the contract as untrusted
//!
//! The text these functions emit is *shell code*. A contract is data, possibly from a document
//! someone else published, so nothing in it is trusted: flag names, command names, the program
//! name and the allowed values must be plain tokens (anything else is skipped, or rejected for
//! the program and command names), and every free-text field (summaries) is quoted for the shell
//! it lands in. A summary such as `'; rm -rf ~ #` is displayed, never executed.
//!
//! ```
//! use argenv_resolve::generate::{self, Command, Program, Shell};
//!
//! let program = Program {
//!     name: "app",
//!     version: "1.0.0",
//!     about: "does things",
//!     commands: &[Command { name: "run", summary: "Run it" }],
//!     exit_status: &[("0", "done"), ("2", "the invocation is wrong")],
//!     see_also: &[],
//!     date: "2026-10-23",
//! };
//! # let records = vec![];
//! let bash = generate::completions(Shell::Bash, &program, &records)?;
//! assert!(bash.contains("complete -F _app app"));
//! let man = generate::man_page(&program, &records)?;
//! assert!(man.starts_with(".TH APP 1 \"2026-10-23\""));
//! # Ok::<(), generate::GenerateError>(())
//! ```

